def get_audio_duration(mp3_path: pathlib.Path) -> float:
    try:
        out = subprocess.check_output(
            [
                "ffprobe",
                "-v",
                "error",
                "-show_entries",
                "format=duration",
                "-of",
                "default=noprint_wrappers=1:nokey=1",
                str(mp3_path),
            ],
            stderr=subprocess.DEVNULL,
        ).decode("utf-8").strip()
        return float(out)
    except Exception:
        return 6.0


def generate_one_scene_audio(task: tuple[str, int, str, pathlib.Path]) -> tuple[str, int, float, int]:
    vid_id, s_idx, text, out_mp3 = task
    out_mp3.parent.mkdir(parents=True, exist_ok=True)
    if not out_mp3.exists() or out_mp3.stat().st_size < 1000:
        tts_script = SUBAGENT_DIR / "tools" / "generate_voice_tts.py"
        subprocess.run(
            [
                sys.executable,
                str(tts_script),
                "--page",
                "4",
                "--text",
                text,
                "--output",
                str(out_mp3),
            ],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            check=False,
        )
    sec = get_audio_duration(out_mp3)
    pad = 40 if s_idx == 5 else 15
    frames = int(math.ceil(sec * 30.0)) + pad
    return vid_id, s_idx, round(sec, 3), frames


